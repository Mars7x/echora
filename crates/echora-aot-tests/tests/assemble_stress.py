#!/usr/bin/env python3
"""Regenerates `src/stress.rs` from `tests/stress.s`.

Needs llvm-mc, llvm-objcopy and llvm-nm. Run from anywhere:
    python3 crates/echora-aot-tests/tests/assemble_stress.py
"""

import pathlib
import struct
import subprocess
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE / "stress.s"
OUTPUT = HERE.parent / "src" / "stress.rs"
PROGRAMS = [
    "claim_cas",
    "claim_llsc",
    "claim_ldadd",
    "ticket",
    "seqlock",
    "pass_acquire",
    "pass_dmb",
]


def main():
    with tempfile.TemporaryDirectory() as tmp:
        obj = pathlib.Path(tmp) / "stress.o"
        binary = pathlib.Path(tmp) / "stress.bin"
        subprocess.run(
            ["llvm-mc", "-triple=aarch64", "-mattr=+lse", "-filetype=obj", str(SOURCE), "-o", str(obj)],
            check=True,
        )
        subprocess.run(
            ["llvm-objcopy", "-O", "binary", "--only-section=.text", str(obj), str(binary)],
            check=True,
        )
        data = binary.read_bytes()
        symbols = subprocess.run(
            ["llvm-nm", str(obj)], check=True, capture_output=True, text=True
        ).stdout
    labels = {}
    for line in symbols.splitlines():
        address, _, name = line.split()
        labels[name] = int(address, 16)
    data += b"\0" * (-len(data) % 0x1000)
    words = struct.unpack(f"<{len(data) // 4}I", data)
    out = [
        "// Generated by `tests/assemble_stress.py` from `tests/stress.s`;\n"
        "// lifted by `build.rs` and run by `tests/stress.rs`. Original code.\n\n"
        "/// Where the stress programs are loaded.\n"
        "pub const STRESS_BASE: u64 = 0x300_0000;\n\n"
        "/// Every program by name, with its entry offset from `STRESS_BASE`.\n"
        "pub const STRESS_ENTRIES: &[(&str, u64)] = &[\n"
    ]
    for name in PROGRAMS:
        out.append(f'    ("{name}", {labels[name]:#x}),\n')
    out.append("];\n\n/// The image, whole pages.\npub const STRESS_WORDS: &[u32] = &[\n")
    for i in range(0, len(words), 8):
        out.append("    " + " ".join(f"{w:#010x}," for w in words[i : i + 8]) + "\n")
    out.append("];\n")
    OUTPUT.write_text("".join(out))


if __name__ == "__main__":
    main()
