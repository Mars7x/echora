#!/usr/bin/env python3
"""Regenerates `src/kernels.rs` from `benches/kernels.s`.

Needs llvm-mc, llvm-objcopy and llvm-objdump. Run from anywhere:
    python3 crates/echora-aot-tests/benches/assemble_kernels.py
"""

import pathlib
import struct
import subprocess
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE / "kernels.s"
OUTPUT = HERE.parent / "src" / "kernels.rs"
NOP = 0xD503201F


def main():
    with tempfile.TemporaryDirectory() as tmp:
        obj = pathlib.Path(tmp) / "kernels.o"
        binary = pathlib.Path(tmp) / "kernels.bin"
        subprocess.run(
            ["llvm-mc", "-triple=aarch64", "-filetype=obj", str(SOURCE), "-o", str(obj)],
            check=True,
        )
        subprocess.run(
            ["llvm-objcopy", "-O", "binary", "--only-section=.text", str(obj), str(binary)],
            check=True,
        )
        data = binary.read_bytes()
        disassembly = subprocess.run(
            ["llvm-objdump", "-d", str(obj)], check=True, capture_output=True, text=True
        ).stdout
        symbols = subprocess.run(
            ["llvm-nm", str(obj)], check=True, capture_output=True, text=True
        ).stdout
    data += b"\0" * (-len(data) % 4)
    words = struct.unpack(f"<{len(data) // 4}I", data)
    labels = {}
    for line in symbols.splitlines():
        address, _, name = line.split()
        labels[name] = int(address, 16)
    comments = {}
    for line in disassembly.splitlines():
        parts = line.split("\t")
        head = parts[0].strip()
        if len(parts) >= 2 and head.endswith(":") and " " in head:
            offset = int(head.split(":")[0], 16)
            comments[offset] = " ".join(p.strip() for p in parts[1:3]).strip()
    size = -(-len(data) // 0x400) * 0x400
    table = labels["table"]
    for offset in range(table, table + 16, 4):
        comments[offset] = "jump table halfwords"

    kernels = ["arith", "memcpy", "memset", "calls", "switch", "vector", "poll", "scalar", "ldst"]
    runs = sorted(
        [(labels[name], name) for name in kernels] + [(labels["leaf_add"], "leaves")]
    )
    out = [
        "// Generated by `benches/assemble_kernels.py` from `benches/kernels.s`;\n"
        "// shared by `build.rs`, which lifts the kernels, and the benchmark,\n"
        "// which runs them. Original code, never copied from a game.\n\n"
        "/// Where the kernel image is loaded: page and window aligned.\n"
        "pub const KERNEL_BASE: u64 = 0x10_0000;\n\n"
        "/// Every kernel by name, with its entry offset from `KERNEL_BASE`.\n"
        "pub const KERNEL_ENTRIES: &[(&str, u64)] = &[\n"
    ]
    for name in kernels:
        out.append(f'    ("{name}", {labels[name]:#x}),\n')
    out.append(
        "];\n\n"
        "/// Bytes of the image: whole 1 KiB windows.\n"
        f"pub const KERNEL_SIZE: u64 = {size:#x};\n\n"
        "/// The image as bytes from `KERNEL_BASE`, with zeros (UDF) in the gaps.\n"
        "pub fn image() -> Vec<u8> {\n"
        "    let mut bytes = vec![0; KERNEL_SIZE as usize];\n"
        "    for &(offset, words) in KERNEL_IMAGE {\n"
        "        for (index, word) in words.iter().enumerate() {\n"
        "            let at = offset as usize + index * 4;\n"
        "            bytes[at..at + 4].copy_from_slice(&word.to_le_bytes());\n"
        "        }\n"
        "    }\n"
        "    bytes\n"
        "}\n\n"
        "/// `(offset, words)` runs of the image; the gaps are never executed.\n"
        "pub const KERNEL_IMAGE: &[(u64, &[u32])] = &[\n"
    )
    for index, (start, _) in enumerate(runs):
        end = runs[index + 1][0] if index + 1 < len(runs) else len(words) * 4
        run = list(words[start // 4 : end // 4])
        while run and run[-1] in (0, NOP):
            run.pop()
        out.append(f"    (\n        {start:#x},\n        &[\n")
        for i, word in enumerate(run):
            comment = comments.get(start + i * 4, "")
            out.append(f"            0x{word >> 16:04x}_{word & 0xFFFF:04x}, // {comment}\n")
        out.append("        ],\n    ),\n")
    out.append("];\n")
    OUTPUT.write_text("".join(out))


if __name__ == "__main__":
    main()
